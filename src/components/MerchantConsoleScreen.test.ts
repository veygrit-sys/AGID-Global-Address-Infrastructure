function extractHostedRedactionHtml(html: string): string {
  const redactionStart = html.indexOf('data-merchant-visible-redaction-contract="hosted-test-vectors"');
  assert.ok(redactionStart >= 0, 'expected hosted redaction contract card in SSR output');
  const redactionEnd = html.indexOf('Vey Ecosystem operations map', redactionStart);
  assert.ok(redactionEnd > redactionStart, 'expected redaction card before Vey Ecosystem section');
  return html.slice(redactionStart, redactionEnd);
}

function extractCarrierCoverageMatrixHtml(html: string): string {
  const coverageStart = html.indexOf('Address Wallet carrier coverage matrix');
  assert.ok(coverageStart >= 0, 'expected carrier coverage matrix in SSR output');
  const coverageEnd = html.indexOf('Hexaship shipment creation readiness', coverageStart);
  assert.ok(coverageEnd > coverageStart, 'expected carrier coverage matrix before shipment readiness section');
  const skipshipLedgerStart = html.indexOf('Skipship webhook ledger', coverageStart);
  assert.ok(skipshipLedgerStart > coverageEnd, 'expected real Skipship webhook ledger after carrier coverage matrix');
  return html.slice(coverageStart, coverageEnd);
}

function renderMerchantConsoleWithWarnings(): { html: string; renderWarnings: string[] } {
  const renderWarnings: string[] = [];
  const originalConsoleError = console.error;

  console.error = (...args: unknown[]) => {
    renderWarnings.push(args.map(String).join(' '));
  };

  try {
    return {
      html: renderToStaticMarkup(React.createElement(MerchantConsoleScreen)),
      renderWarnings,
    };
  } finally {
    console.error = originalConsoleError;
  }
}

function assertNoMerchantConsoleWarnings(renderWarnings: string[]) {
  assert.deepEqual(
    renderWarnings,
    [],
    `expected Merchant Console SSR render to be warning-free, got: ${renderWarnings.join('\n')}`,
  );
}

