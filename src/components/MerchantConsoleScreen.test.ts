test('Merchant Console hosted redaction reader mirrors shared helper refs and counts', () => {
  const hostedContract = loadHostedAddressLoginMerchantVisibleRedactionDisplayContract();
  const adapter = createVeyIdCoreMerchantVisibleRedactionAdapterFixture();
  const expectedRefs = displayRefsFromMerchantVisibleRedactionContract(hostedContract);
  const { html, renderWarnings } = renderMerchantConsoleWithWarnings();
  const redactionHtml = extractHostedRedactionHtml(html);

  assertNoMerchantConsoleWarnings(renderWarnings);
  assert.equal(expectedRefs.length, hostedContract.displayFields.length);
  assert.equal(hostedContract.blockedClassCount, adapter.boundaryGate.requiredBlockedMaterial.length);
  assert.equal(hostedContract.nonClaimCount, adapter.boundaryGate.nonClaims.length);
  assert.equal(hostedContract.renderedMaterialPolicy.showCountsOnly, true);
  assert.equal(hostedContract.renderedMaterialPolicy.copyBlockedMaterialNames, false);
  assert.equal(hostedContract.renderedMaterialPolicy.copyNonClaimText, false);
  assert.match(redactionHtml, new RegExp(`visibleRefs: ${expectedRefs.length}`));
  assert.match(redactionHtml, new RegExp(`blockedClasses: ${adapter.boundaryGate.requiredBlockedMaterial.length}`));
  assert.match(redactionHtml, new RegExp(`nonClaims: ${adapter.boundaryGate.nonClaims.length}`));

  for (const ref of expectedRefs) {
    assert.ok(redactionHtml.includes(ref), `expected hosted redaction card to render ${ref}`);
  }
  for (const material of adapter.boundaryGate.requiredBlockedMaterial) {
    assert.ok(!redactionHtml.includes(material), `hosted redaction card must not render blocked material name ${material}`);
  }
  for (const nonClaim of adapter.boundaryGate.nonClaims) {
    assert.ok(!redactionHtml.includes(nonClaim), `hosted redaction card must not render non-claim text ${nonClaim}`);
  }
});

