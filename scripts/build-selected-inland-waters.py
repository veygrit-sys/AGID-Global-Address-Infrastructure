#!/usr/bin/env python3
"""Keep exact lake/pond hierarchy for representative-water cases, large island lakes, and the reviewed windows."""
import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path
import runpy
import sqlite3
from osgeo import ogr

ROOT = Path(__file__).resolve().parents[1]
helpers = runpy.run_path(str(ROOT / 'scripts/build-global-landforms.py'))
TARGET = ROOT/'src/data/global-islands'

def build(archive):
    ogr.UseExceptions()
    with archive.open('rb') as f:
        if hashlib.file_digest(f,'sha256').hexdigest()!=helpers['GSHHG_SHA']:
            raise ValueError('Expected pinned GSHHG 2.3.7 shapefile archive')
    def dataset(level):
        return ogr.Open(f'/vsizip/{archive.resolve()}/GSHHS_shp/f/GSHHS_f_L{level}.shp')
    sources = {level:dataset(level) for level in (1,2,3,4,6)}
    rows = {}
    mainland={'0','1','2','3','5','6'}
    for level in (1,3,6):
        for feat in sources[level].GetLayer():
            idx = str(feat['id']).split('-')[0]
            if idx in mainland: continue
            poly = feat.geometry()
            area = poly.GetArea()
            if idx not in rows or area > rows[idx][0]:
                p = poly.PointOnSurface();rows[idx]=(area,level,p.GetX(),p.GetY())
    db=sqlite3.connect(':memory:')
    db.execute('create virtual table pins using rtree(id,w,e,s,n)')
    db.executemany('insert into pins values(?,?,?,?,?)',((int(i),x,x,y,y) for i,(_,_,x,y) in rows.items()))
    windows=[w['bounds'] for w in json.loads((ROOT/'scripts/data/landform-worldcover-windows.json').read_text())]
    chosen=defaultdict(list)
    for level in (2,4):
        for feat in sources[level].GetLayer():
            poly=feat.geometry();w,e,s,n=poly.GetEnvelope()
            idx = str(feat['id']).split('-')[0]
            large = level==2 and str(feat['parent_id']) not in mainland and float(feat['area'])>=200
            regional = any(not (x1>e or x2<w or y1>n or y2<s) for x1,y1,x2,y2 in windows)
            select=large or regional
            if not select:
                prep=poly.CreatePreparedGeometry()
                for gid, in db.execute('select id from pins where w<=? and e>=? and s<=? and n>=?',(e,w,n,s)):
                    _,kind,x,y=rows[str(gid)]
                    if (level==4 or kind!=3) and prep.Contains(helpers['shared']['point'](x,y)):
                        select=True;break
            if select:
                chosen[(level,idx)].append(poly.Clone())
    # Remove the complete area of every dry child, including children smaller
    # than one output coordinate. Nested ponds can supply their own positive row.
    children=defaultdict(list)
    for f in sources[3].GetLayer():
        key=(2,str(f['parent_id']).split('-')[0])
        if key in chosen: children[key].append(f.geometry().Clone())
    result=[]
    def pieces(g):
        if g.GetGeometryName()=='POLYGON':
            if not g.IsEmpty(): yield g
        elif g.GetGeometryName() in ('MULTIPOLYGON','GEOMETRYCOLLECTION'):
            for child in g: yield from pieces(child)
    for (level,key),polys in sorted(chosen.items()):
        for raw in polys:
            wet = raw if raw.IsValid() else raw.MakeValid()
            for dry in children[(level,key)]:
                if wet.Intersects(dry):
                    wet=wet.Difference(dry if dry.IsValid() else dry.MakeValid())
            for part in pieces(wet):
                # A strict inset on larger lakes both limits storage and prevents
                # simplification from turning waterline islands into water.
                small=part.GetGeometryRef(0).GetPointCount()<1000
                safe=part.Buffer(-0.0000001 if small else -0.00004)
                if not small: safe=safe.SimplifyPreserveTopology(0.00002)
                for g in pieces(safe):
                    rings=[[[round(x,8),round(y,8)] for x,y in r] for r in helpers['coords'](g)]
                    region=helpers['geo_polygon'](rings)
                    if region.IsValid() and part.Contains(region) and not part.Boundary().Intersects(region):
                        result.append(helpers['shared']['pack'](rings,int(key),100_000_000))
    result.sort(key=lambda row:(row[0],row[1:5]))
    groups=[[]]
    size=2
    for r in result:
        row=helpers['shared']['compact'](r)
        if size+len(row)>380000 and groups[-1]: groups.append([]);size=2
        groups[-1].append(row);size+=len(row)+2
    for i,group in enumerate(groups):
        (TARGET/f'landform-water-{i}.json').write_text('[\n'+',\n'.join(group)+'\n]\n')
    out=['// Generated by scripts/build-selected-inland-waters.py.']
    for i in range(len(groups)):out.append(f"import band{i} from '../data/global-islands/landform-water-{i}.json';")
    out+=['','export const inlandWaterParts = [' + ', '.join(f'band{i}' for i in range(len(groups))) + '];']
    (ROOT/'src/lib/globalInlandWaterParts.ts').write_text('\n'.join(out)+'\n')
    print(len(rows),'island samples;', len(chosen),'selected water IDs;',len(result),'rendered components;',len(groups),'shards')
if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('archive',type=Path);build(ap.parse_args().archive)
